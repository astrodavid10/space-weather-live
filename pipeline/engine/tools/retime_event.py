r"""Re-time an already-rendered event package - no re-render, seconds not hours.

Every dome time in a package is linear in step_seconds (see magneto/plan.py),
so changing the playback duration only means rescaling the manifest's times
and re-emitting the .ds scripts from it. The geometry files are NEVER touched:
their headers quote epochs and real-flow seconds, not dome seconds.

    python tools\retime_event.py --root output\lookback_event --playback-s 180 `
        --drop-layer L1Marker --drop-layer AuroraCurtains --drop-layer WindParticles

Because the scripts are re-emitted by TODAY'S dsexport.ds, a retime also
applies the current show-look to an old package's scripts for free (per-layer
holder intensities, and --drop-layer removes a layer from the player, teardown
and override scripts while its files stay on disk).

THE ONE THING A RETIME CHANGES BESIDES PACE: the parcel stream's apparent
flow rate is wind_stream_s / step_seconds, so a retime multiplies it by
1/factor on a look that was tuned at render time. Decimating wind files is
NOT an alternative (file j's V rows are snapshot j+1 - skipping files morphs
to wrong geometry), so speedups beyond WIND_SPEEDUP_TOL are refused unless
--allow-wind-speedup is given or the WindParticles layer is dropped.
"""
from __future__ import annotations

import argparse
import json
from types import SimpleNamespace
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from dsexport import ds as dsds                              # noqa: E402
from dsexport.publish import write_into                      # noqa: E402
from magneto.plan import rescale_times, wind_speedup         # noqa: E402

STATE_NAME = "current_state.json"
MANIFEST_NAME = "event_frames.json"
BACKUP_NAME = "event_frames.pre-retime.json"
WIND_SPEEDUP_TOL = 1.25


def _parse_iso(s: str) -> datetime:
    return datetime.fromisoformat(str(s).replace("Z", "+00:00"))


def retime(root, playback_s=None, step_seconds=None, drop_layers=(),
           allow_wind_speedup=False, holder_intensities=None,
           shells_hidden=None, dry_run=False) -> dict:
    """Rescale one package's dome times and re-emit its scripts. Returns the
    new manifest (written unless dry_run)."""
    root = Path(root)
    models = root / "Models"
    scripts = root / "Scripts"
    manifest_path = models / MANIFEST_NAME
    manifest = json.loads(manifest_path.read_text(encoding="ascii"))

    old_step = float(manifest["step_seconds"])
    old_playback = float(manifest["playback_s"])
    if (playback_s is None) == (step_seconds is None):
        raise SystemExit("give exactly one of --playback-s / --step-seconds")
    factor = (float(playback_s) / old_playback if playback_s is not None
              else float(step_seconds) / old_step)

    layer_names = [str(lay["name"]) for lay in manifest.get("layers") or []]
    drops = list(dict.fromkeys(drop_layers))
    unknown = [d for d in drops if d not in layer_names]
    if unknown:
        raise SystemExit(f"--drop-layer {unknown}: not in this package "
                         f"(has {layer_names})")
    kept = [n for n in layer_names if n not in drops]
    if not kept:
        raise SystemExit("dropping every layer leaves nothing to play")

    speedup = wind_speedup(factor)
    if ("WindParticles" in kept and speedup > WIND_SPEEDUP_TOL
            and not allow_wind_speedup):
        raise SystemExit(
            f"retime by {factor:.4f} runs the parcel stream {speedup:.2f}x "
            f"its tuned flow rate (tolerance {WIND_SPEEDUP_TOL}). Re-render "
            f"with a scaled --wind-stream-s for an honest stream, or pass "
            f"--allow-wind-speedup, or --drop-layer WindParticles.")

    new = rescale_times(manifest, factor)
    new["layers"] = [lay for lay in new["layers"] if lay["name"] in kept]
    if "WindParticles" in drops:
        new.pop("wind", None)

    # Per-package default visibility of the boundary shells (None = leave as it is).
    # Stored in the manifest because it is a property of the PACKAGE, not of this run:
    # write_event_player reads it back on every future re-emit.
    if shells_hidden is not None:
        new["shells_hidden"] = bool(shells_hidden)

    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if abs(factor - 1.0) < 1e-12 and not drops:
        # same timing, no drops: this is a RE-EMIT (today's dsexport.ds writers
        # over an older package - e.g. adding the dome readout), not a retime
        note = f"RE-EMITTED {stamp}: scripts regenerated by dsexport.ds, timing unchanged"
    else:
        note = (f"RETIMED {stamp}: {old_playback:g}s -> "
                f"{new['playback_s']:g}s playback (factor {factor:.6g})"
                + (f", dropped {', '.join(drops)}" if drops else "")
                + (f", parcel flow x{speedup:.3g} vs the tuned look"
                   if "WindParticles" in kept and abs(speedup - 1) > 1e-9 else ""))
    new.setdefault("provenance_notes", []).append(note)
    new["retimed"] = {
        "at": stamp, "factor": round(factor, 9),
        "from_step_seconds": old_step, "from_playback_s": old_playback,
        "dropped_layers": drops,
        "wind_flow_multiplier": round(speedup, 4),
    }

    eid = str(new["event_id"])
    frame = str(new.get("frame", "j2000"))
    if True:
        # The dome readout strings are a pure function of the event's own state
        # timeline (no geometry involved), so ALWAYS rebuild them with today's
        # hud_text() - packages rendered before the readout existed gain it,
        # and a wording change reaches every re-emitted package. The stored
        # strings are kept only when the timeline is not on this machine.
        try:
            from magneto.render import select_event_states
            from livecore.state import hud_text
            win = new.get("window") or {}
            sts = select_event_states(eid, float(new["step_min"]),
                                      window=(win.get("start"), win.get("stop")))
            if len(sts) == int(new["n_frames"]):
                new["hud"] = [hud_text(s) for s in sts]
                print(f"  readout: {len(sts)} HUD strings rebuilt from the timeline")
                from magneto import plan as plan_mod
                from magneto.render import talking_points
                new["key_moments"] = plan_mod.key_moments(sts)
                new["talking_points"] = talking_points(eid)
                print(f"  talking points: key moments + {len(new['talking_points'])} curated note(s)")
            else:
                print(f"  readout: timeline gives {len(sts)} states for {new['n_frames']} frames"
                      f" - keeping the {len(new.get('hud') or [])} stored strings")
        except Exception as exc:                                       # noqa: BLE001
            print(f"  readout: could not rebuild HUD strings ({exc}) - keeping"
                  f" the {len(new.get('hud') or [])} stored strings")
    n_objects = sum(len(lay["files"]) for lay in new["layers"])
    print(f"{eid}: {old_playback:g}s -> {new['playback_s']:g}s "
          f"(step {old_step:g} -> {new['step_seconds']:g}s), "
          f"{n_objects} objects across {len(kept)} layers"
          + (f", dropped {drops}" if drops else ""))
    if "WindParticles" in kept and abs(speedup - 1) > 1e-9:
        print(f"  NOTE: parcel stream now runs {speedup:.3g}x its tuned "
              f"flow rate (honesty note added to the player header)")
    if dry_run:
        print("  dry run - nothing written")
        return new

    # One-time backup of the as-rendered manifest, then the atomic rewrite.
    backup = models / BACKUP_NAME
    if not backup.exists():
        write_into(backup, manifest_path.read_text(encoding="ascii"))
    write_into(manifest_path, json.dumps(new, indent=1, allow_nan=False))

    # Re-emit every script the render would have emitted, from the new
    # manifest, with today's dsexport.ds (write_into keeps each atomic).
    dsds.write_event_player(new, scripts / dsds.DS_EVENT_PLAYER_FMT.format(eid),
                            new["step_seconds"], frame=frame,
                            intensities=holder_intensities,
                            preload_window=new.get("preload_window"),
                            shell_preset=new.get("shell_preset"))
    dsds.write_shells_js(scripts, new.get("shell_preset"))
    dsds.write_event_teardown(
        new, scripts / dsds.DS_EVENT_TEARDOWN_FMT.format(eid))
    dsds.write_player_js(new, scripts)
    dsds.write_native_aurora_ds(
        new, scripts / dsds.DS_NATIVE_AURORA_FMT.format(eid))
    dsds.write_override_scripts(
        [SimpleNamespace(id=eid, title=new.get("title"))], scripts,
        holders=[lay.get("holder") or lay["name"] for lay in new["layers"]])
    state_path = models / STATE_NAME
    if state_path.exists():
        state = json.loads(state_path.read_text(encoding="ascii"))
        dsds.write_status_ds(state, scripts / dsds.DS_STATUS_NAME,
                             now=_parse_iso(state["epoch"]))
    print(f"  scripts re-emitted into {scripts}")

    # The panel's Shells toggle is told which way to sit by the package's SHIM, which reads
    # shells_hidden out of this manifest at shim-write time. Rewriting the manifest here
    # without rewriting the shim leaves the button asserting the opposite of what the dome
    # is doing - and because a toggle fires the command for the state it thinks it is
    # leaving, pressing Shells then drives them further off instead of raising them.
    # Gannon hit exactly that on 2026-09-17: the re-render wrote its shims and only then ran
    # `retime_event --shells-hidden`, so a package whose holders are black shipped a shim
    # saying shellsOn=1, and the validation capture came back with no shells at all.
    if shells_hidden is not None:
        try:
            from tools.write_shims import write_event_shims
            for p in write_event_shims(eid):
                print(f"  shim resynced: {p.name}")
        except Exception as exc:                                       # noqa: BLE001
            # Never fail the re-emit over this, but never let it pass quietly either:
            # a silent default is what made the original bug invisible.
            print(f"  WARNING: shells_hidden={bool(shells_hidden)} was written to the "
                  f"manifest but the shim could NOT be regenerated ({exc}). Run "
                  f"`python -m tools.write_shims --all` or the panel's Shells toggle "
                  f"will sit the wrong way for this package.")

    print(f"  models untouched ({models / MANIFEST_NAME} rewritten, "
          f"original kept as {BACKUP_NAME})")
    return new


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="python tools\\retime_event.py", description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True,
                    help="package root (its Models/ + Scripts/)")
    ap.add_argument("--playback-s", type=float, default=None,
                    help="target total playback in dome seconds")
    ap.add_argument("--step-seconds", type=float, default=None,
                    help="target dome seconds per field step "
                         "(alternative to --playback-s)")
    ap.add_argument("--drop-layer", action="append", default=[],
                    metavar="NAME",
                    help="remove a layer from the scripts (files stay on "
                         "disk); repeatable")
    ap.add_argument("--allow-wind-speedup", action="store_true",
                    help=f"accept a parcel-flow speedup beyond "
                         f"{WIND_SPEEDUP_TOL}x")
    ap.add_argument("--holder-intensity", action="append", default=[],
                    metavar="LAYER=NN",
                    help="starting intensity override for one holder, e.g. "
                         "BowShock=25 (repeatable)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--shells-hidden", dest="shells_hidden", action="store_true", default=None,
                    help="this package starts with its boundary shells hidden (holder colour "
                         "0 0 0); the panel's Shells toggle raises them")
    ap.add_argument("--shells-visible", dest="shells_hidden", action="store_false",
                    help="this package starts with its boundary shells visible (the default)")
    args = ap.parse_args(argv)

    intensities = {}
    for spec in args.holder_intensity:
        layer, _, value = str(spec).partition("=")
        if not value:
            ap.error(f"--holder-intensity wants LAYER=NN, got {spec!r}")
        intensities[layer] = float(value)

    retime(args.root, playback_s=args.playback_s,
           step_seconds=args.step_seconds, drop_layers=args.drop_layer,
           allow_wind_speedup=args.allow_wind_speedup,
           holder_intensities=intensities or None,
           shells_hidden=args.shells_hidden, dry_run=args.dry_run)
    return 0


if __name__ == "__main__":
    sys.exit(main())
